"""Generate the index of the rules, the module `lorecraft.rules.index`.

The module is written as `index.py` into `src/lorecraft/rules`, unless `--outdir` names another directory.

The registry stays the only source of rules: each row is derived from a declaration `Registry.load` holds, so the
index cannot list a rule the registry does not. It exists so that a reader that only needs to know which codes exist
can read plain strings and tuples without importing the rules engine. The whole module is generated, lookups
included, then formatted, so that `just fmt` leaves it unchanged.
"""

import argparse
import subprocess
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Final, assert_never

from lorecraft import rules
from lorecraft.rules.declaration import EngineCondition, Level, RemovedRule, Rule, RuleDeclaration, Severity
from lorecraft.rules.registry import Registry

_DEFAULT_OUTDIR: Final[Path] = Path('src/lorecraft/rules')

_FILENAME: Final[str] = 'index.py'

# What the module is made of before its data: its docstring, its import and the types of its rows and lookups. The
# words of a level and of a severity are filled in from the enums by `render_module`, so they are never spelled twice.
_PREAMBLE_TEMPLATE: Final[
    str
] = '''"""The identity of every rule, as strings and tuples, readable without importing the rules engine.

Generated by `lorecraft_gen.rule_index` with `just gen-rule-index` from the registry, and never edited by hand:
`just gen-check` fails when it is out of date. The registry stays the only source of rules; this module is derived
from it and `just gen-check` holds the two equal.

Importing it loads none of `lorecraft.rules.declaration`, `lorecraft.rules.subject`, `lorecraft.rules.registry`,
`lorecraft.project` nor `lorecraft.engine`, which is why its types are plain named tuples of its own, one per kind of
row: a row is read by attribute, and its class tells its kind.
"""

from typing import Final, Literal, NamedTuple, assert_never

# These two mirror the enums of `lorecraft.rules.declaration`, which this module must not import; the generator fills
# in the words from the enums, so they are not spelled by hand.
type Level = Literal[{levels}]
"""How a rule in service is configured; the words a configuration spells it with."""

type Severity = Literal[{severities}]
"""How an engine condition is reported; the words the output spells it with."""


class RuleInServiceRow(NamedTuple):
    """A rule in service: its code, name, configured level and alias codes.

    Attributes:
        code: The rule's code, such as `OUT004`.
        name: The rule's name, such as `empty-section`.
        level: How the rule is configured by default.
        aliases: The alias codes the rule declares, such as `MD040`; none for most rules.
    """

    code: str
    name: str
    level: Level
    aliases: tuple[str, ...]


class RemovedRuleRow(NamedTuple):
    """A removed rule: its code and name, which `lorecraft rule` still looks up.

    Attributes:
        code: The removed rule's code.
        name: The removed rule's name.
    """

    code: str
    name: str


class EngineConditionRow(NamedTuple):
    """An engine condition: its code, name and the severity it is always reported at.

    Attributes:
        code: The condition's code, such as `LC001`.
        name: The condition's name, such as `invalid-utf8`.
        severity: The severity every report of the condition has.
    """

    code: str
    name: str
    severity: Severity


type RuleRow = RuleInServiceRow | RemovedRuleRow | EngineConditionRow
"""One declaration's row, of the kind its class tells."""

_CODE_DIGITS: Final[int] = 3
"""How many digits end a code, after its group's prefix."""
'''

# The lookups, which read the two tuples above them. A group of removed rules alone is not in `GROUPS`, as the
# registry does not find it by its prefix: nothing in it could be selected.
_LOOKUPS: Final[str] = '''

def find(key: str) -> RuleRow | None:
    """The row whose code, name or alias code is `key`, or None when none is.

    Args:
        key: A code as printed, such as `OUT004`, a name, such as `empty-section`, or an alias code, such as `MD040`.
    """
    for row in RULES:
        if key == row.code or key == row.name or key in _alias_codes(row):
            return row
    return None


def group_title(prefix: str) -> str | None:
    """The title of the group with this prefix, or None when no rule in service nor condition is in it.

    The prefix is matched as spelled, so text no prefix could be, such as `out`, is not an error: no group has it.

    Args:
        prefix: A group's prefix, such as `OUT`.
    """
    for group_prefix, title in GROUPS:
        if group_prefix == prefix:
            return title
    return None


def codes_in_group(prefix: str) -> tuple[str, ...]:
    """The codes of the group with this prefix, in code order, removed rules included; none for an unknown prefix.

    Args:
        prefix: A group's prefix, such as `OUT`.
    """
    return tuple(row.code for row in RULES if row.code[:-_CODE_DIGITS] == prefix)


def codes_with_prefix(prefix: str) -> tuple[str, ...]:
    """The codes that start with this text, in code order; none when no code does.

    A group's prefix selects its whole group, and a longer one, such as `OUT00`, a run of its numbers.

    Args:
        prefix: The start of a code, such as `OUT` or `OUT00`.
    """
    return tuple(row.code for row in RULES if row.code.startswith(prefix))


def _alias_codes(row: RuleRow) -> tuple[str, ...]:
    """The alias codes of a row, which only a rule in service declares.

    Args:
        row: A row of any kind.
    """
    match row:
        case RuleInServiceRow():
            return row.aliases
        case RemovedRuleRow() | EngineConditionRow():
            return ()
        case _:
            assert_never(row)
'''


def build_groups(registry: Registry) -> tuple[tuple[str, str], ...]:
    """The `(prefix, title)` of every group a rule in service or an engine condition is in, in prefix order.

    Args:
        registry: The registry to derive the groups from.
    """
    titles: dict[str, str] = {}
    for declaration in registry.rules:
        if not issubclass(declaration, RemovedRule):
            group = declaration.CODE.group
            titles[str(group.prefix)] = group.title
    return tuple(sorted(titles.items()))


def build_rows(registry: Registry) -> tuple[str, ...]:
    """The source of one row per declaration the registry holds, as an expression of the index's row types.

    Args:
        registry: The registry to derive the rows from, whose code order the rows keep.
    """
    return tuple(_build_row(declaration) for declaration in registry.rules)


def render_module(groups: tuple[tuple[str, str], ...], rows: tuple[str, ...]) -> str:
    """The Python module that declares these groups and rows, and the functions that look them up.

    The text is not formatted: `write_rule_index` runs the formatter over the file it writes.

    Args:
        groups: The `(prefix, title)` pairs, in prefix order.
        rows: The source of each rule row, in code order.
    """
    preamble = _PREAMBLE_TEMPLATE.format(
        levels=_literal_words(level.value for level in Level),
        severities=_literal_words(severity.value for severity in Severity),
    )
    lines = [preamble, 'GROUPS: Final[tuple[tuple[str, str], ...]] = (', '    # prefix, title']
    lines += [f'    {group!r},' for group in groups]
    lines += [
        ')',
        '',
        'RULES: Final[tuple[RuleRow, ...]] = (',
    ]
    lines += [f'    {row},' for row in rows]
    lines += [')']
    return '\n'.join(lines) + '\n' + _LOOKUPS


def _literal_words(words: Iterable[str]) -> str:
    """The words as the members of a `Literal`, such as `'allow', 'warn', 'deny'`.

    Args:
        words: The words, in the order the enum declares them.
    """
    return ', '.join(repr(word) for word in words)


def _build_row(declaration: RuleDeclaration) -> str:
    """The source of the row of one declaration: a call of the row type of its kind.

    A `match` class pattern tests an instance, not a class, so the branch on a declaration's kind is an
    `issubclass` chain, closed by `assert_never`.

    Args:
        declaration: A rule in service, a removed rule or an engine condition.
    """
    code = str(declaration.CODE)
    name = str(declaration.NAME)
    if issubclass(declaration, Rule):
        aliases = tuple(str(alias) for alias in declaration.ALIASES)
        level = declaration.LEVEL.value
        return f'RuleInServiceRow(code={code!r}, name={name!r}, level={level!r}, aliases={aliases!r})'
    if issubclass(declaration, RemovedRule):
        return f'RemovedRuleRow(code={code!r}, name={name!r})'
    if issubclass(declaration, EngineCondition):
        severity = declaration.SEVERITY.value
        return f'EngineConditionRow(code={code!r}, name={name!r}, severity={severity!r})'
    assert_never(declaration)


def write_rule_index(outdir: Path) -> Path:
    """Write the module of the index of every rule in the registry, formatted, into a directory.

    Args:
        outdir: The directory `index.py` goes into, which must exist; the file is overwritten.

    Returns:
        The file written.

    Raises:
        subprocess.CalledProcessError: If the formatter fails over the file.
    """
    registry = Registry.load(rules)
    path = outdir / _FILENAME
    path.write_text(render_module(build_groups(registry), build_rows(registry)), encoding='utf-8')
    subprocess.run([sys.executable, '-m', 'ruff', 'format', '--quiet', str(path)], check=True)
    return path


def main() -> None:
    """Write the rule index, and print the file written.

    The output directory is the `--outdir` option, and `src/lorecraft/rules` when it is absent.
    """
    parser = argparse.ArgumentParser(description='Generate the index of the rules.')
    parser.add_argument(
        '--outdir',
        type=Path,
        default=_DEFAULT_OUTDIR,
        help=f'the directory {_FILENAME} is written into, which must exist (default: %(default)s)',
    )
    outdir: Path = parser.parse_args().outdir

    print('Generating the rule index...')
    print(f'  {write_rule_index(outdir)}')


if __name__ == '__main__':
    main()
