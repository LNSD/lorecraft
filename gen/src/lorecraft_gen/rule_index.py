"""Generate the index of the rules, the module `lorecraft.rules.index`.

The module is written as `index.py` into `src/lorecraft/rules`, unless `--outdir` names another directory.

The registry stays the only source of rules: each row is derived from a declaration `Registry.load` holds, so the
index cannot list a rule the registry does not. It exists so that a reader that only needs rule identities can read
plain strings and frozen records without importing the rules engine. The whole module is generated, lookups
included, then formatted, so that `just fmt` leaves it unchanged.
"""

import argparse
import subprocess
import sys
from pathlib import Path
from typing import Final, assert_never

from lorecraft import rules
from lorecraft.rules.declaration import EngineCondition, RemovedRule, Rule, RuleDeclaration
from lorecraft.rules.identity import RuleCode
from lorecraft.rules.registry import Registry

_DEFAULT_OUTDIR: Final[Path] = Path('src/lorecraft/rules')

_FILENAME: Final[str] = 'index.py'

# What the module is made of before its data: its docstring and imports.
_PREAMBLE: Final[
    str
] = '''"""The identity of every rule, as strings and frozen records, readable without importing the rules engine.

Generated by `lorecraft_gen.rule_index` with `just gen-rule-index` from the registry, and never edited by hand:
the CI `gen-check` job fails when it is out of date. The registry stays the only source of rules; this module is derived
from it and the CI `gen-check` job holds the two equal.

Importing it loads none of `lorecraft.rules.declaration`, `lorecraft.rules.subject`, `lorecraft.rules.registry`,
`lorecraft.project` nor `lorecraft.engine`: its rows use built-in types deliberately for load speed, with no Lorecraft
module imports.
"""

from typing import Final, NamedTuple

CODE_DIGITS: Final[int] = {code_digits}
"""How many digits end a code, after its group's prefix."""

class RuleRow(NamedTuple):
    """One active rule and its aliases."""

    code: str
    name: str
    level: str
    aliases: tuple[str, ...]

class RemovedRuleRow(NamedTuple):
    """One removed rule."""

    code: str
    name: str

class ConditionRow(NamedTuple):
    """One engine condition and its severity."""

    code: str
    name: str
    severity: str

type RuleIndexRow = RuleRow | RemovedRuleRow | ConditionRow
'''

# The lookup reads the rule rows above it.
_LOOKUPS: Final[str] = '''

def find(key: str) -> RuleIndexRow | None:
    """The row whose code, name or alias code is `key`, or None when none is.

    A row is a rule, removed rule or engine condition record.

    Args:
        key: A code as printed, such as `LC304`, a name, such as `empty-section`, or an alias code, such as `MD040`.
    """
    for row in RULES:
        if key == row.code or key == row.name or isinstance(row, RuleRow) and key in row.aliases:
            return row
    return None


'''


def render_rows(registry: Registry) -> tuple[str, ...]:
    """The source lines that construct one record for each registry declaration.

    Args:
        registry: The registry to derive the rows from, whose code order the rows keep.
    """
    return tuple(_render_row(declaration) for declaration in registry.rules)


def render_module(rows: tuple[str, ...]) -> str:
    """The Python module that declares rows and the lookup function.

    The text is not formatted: `write_rule_index` runs the formatter over the file it writes.
    """
    lines = [
        _PREAMBLE.format(code_digits=RuleCode.DIGITS),
        'RULES: Final[tuple[RuleIndexRow, ...]] = (',
    ]
    lines += [f'    {row}' for row in rows]
    lines += [')']
    return '\n'.join(lines) + '\n' + _LOOKUPS


def _render_row(declaration: RuleDeclaration) -> str:
    """The source line that constructs one declaration's record.

    A `match` class pattern tests an instance, not a class, so the branch on a declaration's kind is an
    `issubclass` chain, closed by `assert_never`.

    Args:
        declaration: A rule in service, a removed rule or an engine condition.
    """
    name = str(declaration.NAME)
    if issubclass(declaration, Rule):
        code = str(declaration.CODE)
        aliases = ', '.join(repr(str(alias)) for alias in declaration.ALIASES)
        alias_tuple = f'({aliases},)' if len(declaration.ALIASES) == 1 else f'({aliases})'
        return f'RuleRow({code!r}, {name!r}, {declaration.LEVEL.value!r}, {alias_tuple}),'
    if issubclass(declaration, RemovedRule):
        return f'RemovedRuleRow({str(declaration.CODE)!r}, {name!r}),'
    if issubclass(declaration, EngineCondition):
        return f'ConditionRow({str(declaration.CODE)!r}, {name!r}, {declaration.SEVERITY.value!r}),'
    assert_never(declaration)


def write_rule_index(outdir: Path) -> Path:
    """Write the module of the index of every rule in the registry, formatted, into a directory.

    Args:
        outdir: The directory `index.py` goes into, which must exist; the file is overwritten.

    Returns:
        The file written.

    Raises:
        subprocess.CalledProcessError: If the formatter fails over the file.
    """
    registry = Registry.load(rules)
    path = outdir / _FILENAME
    path.write_text(render_module(render_rows(registry)), encoding='utf-8')
    subprocess.run([sys.executable, '-m', 'ruff', 'format', '--quiet', str(path)], check=True)
    return path


def main() -> None:
    """Write the rule index, and print the file written.

    The output directory is the `--outdir` option, and `src/lorecraft/rules` when it is absent.
    """
    parser = argparse.ArgumentParser(description='Generate the index of the rules.')
    parser.add_argument(
        '--outdir',
        type=Path,
        default=_DEFAULT_OUTDIR,
        help=f'the directory {_FILENAME} is written into, which must exist (default: %(default)s)',
    )
    outdir: Path = parser.parse_args().outdir

    print('Generating the rule index...')
    print(f'  {write_rule_index(outdir)}')


if __name__ == '__main__':
    main()
