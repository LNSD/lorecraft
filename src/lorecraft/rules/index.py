"""The identity of every rule, as strings and tuples, readable without importing the rules engine.

Generated by `lorecraft_gen.rule_index` with `just gen-rule-index` from the registry, and never edited by hand:
`just gen-check` fails when it is out of date. The registry stays the only source of rules; this module is derived
from it and `just gen-check` holds the two equal.

Importing it loads none of `lorecraft.rules.declaration`, `lorecraft.rules.subject`, `lorecraft.rules.registry`,
`lorecraft.project` nor `lorecraft.engine`, which is why its types are plain named tuples of its own, one per kind of
row: a row is read by attribute, and its class tells its kind.
"""

from typing import Final, Literal, NamedTuple, assert_never

# These two mirror the enums of `lorecraft.rules.declaration`, which this module must not import; the generator fills
# in the words from the enums, so they are not spelled by hand.
type Level = Literal['allow', 'warn', 'deny']
"""How a rule in service is configured; the words a configuration spells it with."""

type Severity = Literal['error', 'warning']
"""How an engine condition is reported; the words the output spells it with."""


class RuleInServiceRow(NamedTuple):
    """A rule in service: its code, name, configured level and alias codes.

    Attributes:
        code: The rule's code, such as `OUT004`.
        name: The rule's name, such as `empty-section`.
        level: How the rule is configured by default.
        aliases: The alias codes the rule declares, such as `MD040`; none for most rules.
    """

    code: str
    name: str
    level: Level
    aliases: tuple[str, ...]


class RemovedRuleRow(NamedTuple):
    """A removed rule: its code and name, which `lorecraft rule` still looks up.

    Attributes:
        code: The removed rule's code.
        name: The removed rule's name.
    """

    code: str
    name: str


class EngineConditionRow(NamedTuple):
    """An engine condition: its code, name and the severity it is always reported at.

    Attributes:
        code: The condition's code, such as `LC001`.
        name: The condition's name, such as `invalid-utf8`.
        severity: The severity every report of the condition has.
    """

    code: str
    name: str
    severity: Severity


type RuleRow = RuleInServiceRow | RemovedRuleRow | EngineConditionRow
"""One declaration's row, of the kind its class tells."""

