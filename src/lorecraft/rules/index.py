"""The identity of every rule, as strings and frozen records, readable without importing the rules engine.

Generated by `lorecraft_gen.rule_index` with `just gen-rule-index` from the registry, and never edited by hand:
the CI `gen-check` job fails when it is out of date. The registry stays the only source of rules; this module is derived
from it and the CI `gen-check` job holds the two equal.

Importing it loads none of `lorecraft.rules.declaration`, `lorecraft.rules.subject`, `lorecraft.rules.registry`,
`lorecraft.project` nor `lorecraft.engine`: its rows use built-in types deliberately for load speed, with no Lorecraft
module imports.
"""

