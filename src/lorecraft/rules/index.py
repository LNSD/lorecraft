"""The prefix reserved for engine conditions."""


class RuleRow(NamedTuple):
    """One active rule and its aliases."""

    code: str
    name: str
    level: str
    aliases: tuple[str, ...]


class RemovedRuleRow(NamedTuple):
    """One removed rule."""

    code: str
    name: str


class ConditionRow(NamedTuple):
    """One engine condition and its severity."""

    code: str
    name: str
    severity: str


